#!/usr/bin/env python3
"""Writes theme_quest/src/star.c: a 12x12 five-pointed star as a 4-bit coverage mask (CYDUI_BITMAP_A4: two pixels per
byte, high nibble first). Coverage comes from 8x8 supersampling of a regular star, so the edges are smooth. Deterministic.
"""
import math

SIZE = 12
SS = 8
R_OUT = SIZE / 2 - 0.2
R_IN = R_OUT * 0.40


def points():
    pts = []
    for k in range(10):
        r = R_OUT if k % 2 == 0 else R_IN
        a = -math.pi / 2 + k * math.pi / 5
        pts.append((SIZE / 2 + r * math.cos(a), SIZE / 2 + 0.6 + r * math.sin(a)))
    return pts


def inside(poly, x, y):
    c = False
    j = len(poly) - 1
    for i in range(len(poly)):
        xi, yi = poly[i]
        xj, yj = poly[j]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            c = not c
        j = i
    return c


def main():
    poly = points()
    print("/* generated by tools/gen_star.py - do not edit */")
    print('#include "todo/theme_quest.h"')
    print()
    print("const uint8_t todo_star_mask[TODO_STAR_SIZE / 2 * TODO_STAR_SIZE] = {")
    for py in range(SIZE):
        row = []
        for px in range(SIZE):
            n = sum(inside(poly, px + (sx + 0.5) / SS, py + (sy + 0.5) / SS) for sy in range(SS) for sx in range(SS))
            row.append(round(15 * n / (SS * SS)))
        print("    " + ", ".join("0x%02X" % ((row[i] << 4) | row[i + 1]) for i in range(0, SIZE, 2)) + ",")
    print("};")


main()
