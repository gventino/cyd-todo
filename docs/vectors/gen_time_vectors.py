#!/usr/bin/env python3
"""Writes docs/vectors/time.tsv: calendar and time-zone facts computed with Python's own datetime module.

The firmware (C, firmware/components/model) and the server (Rust, server/src/timeutil.rs) both read the file
in their tests, so the two implementations of the same arithmetic cannot drift apart. The expected values come
from a third, independent implementation (the standard library), not from either of them.

Lines are tab separated; `#` starts a comment.
  civil   <days since 1970-01-01>  <year> <month> <day> <weekday, Monday 0>
  local   <epoch seconds>  <offset minutes east>  <YYYY-MM-DDTHH:MM in that zone>
  parse   <YYYY-MM-DDTHH:MM[:SS]>  <offset>  <epoch seconds | none>
  window  <year> <month> <offset>  <from epoch>  <to epoch>      (the UTC window of a local month)

Usage: gen_time_vectors.py > docs/vectors/time.tsv
"""
from datetime import date, datetime, timedelta, timezone

OFFSETS = [-180, 0, 330, 840, -720, 60]
EPOCH0 = date(1970, 1, 1)


def utc(y, m, d, hh=0, mm=0, ss=0):
    return int(datetime(y, m, d, hh, mm, ss, tzinfo=timezone.utc).timestamp())


def main():
    out = ["# generated by docs/vectors/gen_time_vectors.py - do not edit"]
    # every day of 2026-2028, and the ends of the supported range
    days = [(date(2026, 1, 1) + timedelta(n)) for n in range(0, 1096)]
    days += [date(2000, 1, 1), date(2000, 2, 29), date(2024, 2, 29), date(2099, 12, 31), date(1970, 1, 1), date(2100, 3, 1)]
    for d in days:
        n = (d - EPOCH0).days
        out.append(f"civil\t{n}\t{d.year}\t{d.month}\t{d.day}\t{d.weekday()}")
    # instants around midnight and month ends, in every zone
    bases = [utc(2026, 12, 2, 17), utc(2026, 12, 31, 23, 59, 59), utc(2027, 1, 1), utc(2028, 2, 29, 12), utc(2028, 3, 1), utc(2026, 11, 30, 22)]
    for b in bases:
        for off in OFFSETS:
            for delta in (-3601, -1, 0, 1, 59, 60, 3600, 86399, 86400):
                t = b + delta
                z = datetime.fromtimestamp(t, tz=timezone(timedelta(minutes=off)))
                out.append(f"local\t{t}\t{off}\t{z.strftime('%Y-%m-%dT%H:%M')}")
    # reading what a browser sends
    good = ["2026-12-24T23:30", "2026-12-24T23:30:15", "2028-02-29T00:00", "2027-01-01T00:15", "2026-12-31T23:59", "2000-01-01T00:00", "2099-12-31T23:59"]
    for s in good:
        for off in OFFSETS:
            z = datetime.strptime(s[:16], "%Y-%m-%dT%H:%M").replace(tzinfo=timezone(timedelta(minutes=off)))
            t = int(z.timestamp()) + (int(s[17:19]) if len(s) == 19 else 0)
            out.append(f"parse\t{s}\t{off}\t{t}")
    bad = ["", "2026-12-24", "2026-12-24 23:30", "2026-12-24T24:00", "2026-12-24T23:60", "2026-13-01T10:00", "2027-02-29T10:00", "2026-12-24T23:30:60",
           "2026-12-24T23:30:", "2026-12-24T23:30Z", "26-12-24T23:30", "2026/12/24T23:30", "2026-12-24t23:30", " 2026-12-24T23:30", "2026-12-24T23:30 ", "2026-04-31T10:00"]
    for s in bad:
        out.append(f"parse\t{s}\t0\tnone")
    # the UTC window of a local month
    for y in (2026, 2027, 2028):
        for m in range(1, 13):
            for off in OFFSETS:
                ny, nm = (y + 1, 1) if m == 12 else (y, m + 1)
                local_from = utc(y, m, 1) - off * 60
                local_to = utc(ny, nm, 1) - off * 60
                out.append(f"window\t{y}\t{m}\t{off}\t{local_from}\t{local_to}")
    print("\n".join(out))


main()
